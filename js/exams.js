  // الأسئلة حسب المستوى والمسار
  function examFor(level, track, science) {
    const pick = (k, n) => (BANK[k + '-' + level] || []).slice().sort(() => Math.random() - .5).slice(0, n);
    if (track === 'general') {
      let qs = [];
      ['aqida', 'fiqh', 'hadith', 'mustalah', 'tafsir', 'usul', 'lugha', 'sira', 'adab'].forEach(k => { qs = qs.concat(pick(k, 3).map(q => [...q, k])); });
      return qs;
    }
    const sci = science === 'fiqh' ? ['fiqh', 'usul'] : [science];
    return sci.flatMap(k => pick(k, 10).map(q => [...q, k]));
  }

  // ===== محرك الاختيار من متعدد =====
  // qs: [سؤال، خيارات، الصحيح، توضيح]؛ تُخلط الخيارات في كل مرة
  function runQuiz(box, { title, sub, qs, pass = 70, onDone }) {
    const Q = qs.map(([q, opts, a, why]) => { const ord = opts.map((o, i) => i).sort(() => Math.random() - .5); return { q, opts: ord.map(i => opts[i]), a: ord.indexOf(a), why }; });
    box.innerHTML = `${title ? `<h2>${esc(title)}</h2>` : ''}${sub ? `<div class="sub">${sub}</div>` : ''}
      <form class="quiz">${Q.map((x, i) => `<div class="card" data-qi="${i}"><b>${AR.toArabicDigits(i + 1)}. ${esc(x.q)}</b>
        ${x.opts.map((o, j) => `<label class="quiz-opt"><input type="radio" name="q${i}" value="${j}"> ${esc(o)}</label>`).join('')}<div class="quiz-why"></div></div>`).join('')}
        <button class="btn primary">✔ تصحيح الإجابات</button></form><div class="quiz-res"></div>`;
    box.querySelector('form').onsubmit = e => {
      e.preventDefault();
      let ok = 0;
      Q.forEach((x, i) => {
        const card = box.querySelector(`[data-qi="${i}"]`), v = (box.querySelector(`input[name=q${i}]:checked`) || {}).value;
        const right = +v === x.a; if (right) ok++;
        card.querySelectorAll('.quiz-opt').forEach((l, j) => { l.classList.toggle('opt-ok', j === x.a); l.classList.toggle('opt-bad', String(j) === v && !right); l.querySelector('input').disabled = true; });
        card.querySelector('.quiz-why').innerHTML = (right ? '✅ ' : v === undefined ? '⏺ لم تُجب — ' : '❌ ') + esc(x.why || '');
      });
      const pct = Q.length ? Math.round(100 * ok / Q.length) : 0, passed = pct >= pass;
      box.querySelector('form button').remove();
      const res = box.querySelector('.quiz-res');
      res.innerHTML = `<div class="card" style="text-align:center"><div style="font-size:40px;font-weight:700;color:${passed ? 'var(--brand)' : 'var(--red)'}">${pct}٪</div><div>${ok} من ${Q.length} — ${passed ? '🎉 ناجح، بارك الله فيك' : 'لم تبلغ ' + pass + '٪ — راجع الإجابات الموضَّحة وأعد المحاولة'}</div></div>`;
      res.scrollIntoView({ behavior: 'smooth' });
      onDone && onDone({ pct, ok, total: Q.length, passed });
    };
  }

  window.EXAMS = { BANK, examFor, runQuiz };
