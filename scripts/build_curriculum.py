def resolve(q, death):
    if not q: return None
    nq = n(q)
    cands = [c for c in cat if nq in n(c['t'])]
    if death: cands = [c for c in cands if abs(c['d'] - death) <= 3] or cands
    cands.sort(key=lambda c: (not n(c['t']).startswith(nq), any(w in n(c['t']) for w in ('تخريج', 'شرح ' + nq)) and not nq.startswith('شرح'), c['s'] != 'p', len(c['t'])))
    return cands[0] if cands else None
missing = []
def build(group):
    out = {}
    for key, (name, books) in group.items():
        items = []
        for k, (lvl, t, a, q, death, lib) in enumerate(books):
            e = {'id': f'{key}-{k}', 'level': lvl, 't': t, 'a': a}
            if lib: e['lib'] = lib
            else:
                c = resolve(q, death)
                if c: e['v'] = c['v']; e['u'] = c['u']; e['c'] = c['c']; e['found'] = c['t']
                else: e['q'] = q; missing.append(t)
            items.append(e)
        out[key] = {'name': name, 'books': items}
    return out
